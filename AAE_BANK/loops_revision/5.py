# PROBLEM 5 — SUM 1 TO N
# ============================================================
# Task:
# Calculate the sum of all numbers from 1 to N.
#
# Example:
# N = 5
#
# Answer:
# 15
#
# Function:
# def sum_n(n):
#     ...

def sumn(n):

    total = 0 

    for i in range(1,n+1):
        total += i

    return total 

    






